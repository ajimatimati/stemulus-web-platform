async function buildMinified() {
  try {
    const result = await terser.minify(bundle, {
      compress: true,
      mangle: true
    });
    fs.writeFileSync(minifiedPath, result.code, 'utf8');
    console.log('Success: stemulus-portal-features.min.js created.');
  } catch (err) {
    console.error('Error minifying stemulus-portal-features:', err);
    process.exit(1);
  }
}

