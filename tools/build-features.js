function stripModuleSyntax(code) {
  let cleaned = code.replace(/^\s*import\s+[^;]+;\s*$/gm, '');
  cleaned = cleaned.replace(/^\s*export\s+default\s+[^;]+;\s*$/gm, '');
  cleaned = cleaned.replace(/^\s*export\s*\{[^}]*\};?\s*$/gm, '');
  cleaned = cleaned.replace(/^\s*export\s+(async\s+function\s+)/gm, '$1');
  cleaned = cleaned.replace(/^\s*export\s+(function\s+)/gm, '$1');
  cleaned = cleaned.replace(/^\s*export\s+(const\s+)/gm, '$1');
  cleaned = cleaned.replace(/^\s*export\s+(let\s+)/gm, '$1');
  cleaned = cleaned.replace(/^\s*export\s+(var\s+)/gm, '$1');
  cleaned = cleaned.replace(/if\s*\(typeof window !== 'undefined'\)\s*\{[\s\S]*?\}\s*$/g, '');
  return cleaned;
}

